"""Ahead-of-time compiler, in the spirit of `python -m triton.tools.compile`.

    python -m piton.tools.compile examples/kernels.py --kernel-name matmul_kernel \
        --signature "a_ptr=*fp32,b_ptr=*fp32,c_ptr=*fp32,M=i32,N=i32,stride_am=i32,stride_bk=i32,stride_cm=i32" \
        --constants "K=512,stride_ak=1,stride_bn=1,stride_cn=1,BLOCK_SIZE_M=8,BLOCK_SIZE_N=64,BLOCK_SIZE_K=4,GROUP_SIZE_M=4" \
        --out-name matmul -o build/

writes build/matmul.qasm (vc4asm source), build/matmul.c and build/matmul.h.
The C files contain the machine code and a launcher for bare-metal programs
built on pi/runtime/piton_rt.c:

    matmul_args_t args = { .a_ptr = A.bus, ..., .M = 512, ... };
    uint32_t usec = matmul_launch(&args, grid_x, 1, 1);
"""

from __future__ import annotations

import argparse
import importlib.util
import os
import sys

from .. import compiler
from ..qpu.asm import find_vc4asm, vc4asm_assemble


def _load_kernel(path: str, name: str):
    spec = importlib.util.spec_from_file_location(os.path.splitext(os.path.basename(path))[0], path)
    mod = importlib.util.module_from_spec(spec)
    sys.path.insert(0, os.path.dirname(os.path.abspath(path)))
    spec.loader.exec_module(mod)
    return getattr(mod, name)


def _parse_kv(text: str) -> dict:
    out = {}
    for item in filter(None, (t.strip() for t in text.split(","))):
        k, v = item.split("=", 1)
        v = v.strip()
        try:
            out[k.strip()] = int(v, 0)
        except ValueError:
            try:
                out[k.strip()] = float(v)
            except ValueError:
                out[k.strip()] = v
    return out


C_TYPES = {"*fp32": "uint32_t", "*i32": "uint32_t", "*u32": "uint32_t", "i32": "int32_t",
           "u32": "uint32_t", "fp32": "float", "i1": "int32_t"}


def emit_c(ck, out_name: str) -> tuple:
    words = ck.words
    sym = out_name
    args = [(n, t) for n, t in ck.signature.items()]
    lines_h = [
        f"// Generated by piton.tools.compile from Triton kernel `{ck.name}`.",
        f"// constants: {', '.join(f'{k}={v}' for k, v in ck.constants.items())}",
        f"#ifndef {sym.upper()}_H", f"#define {sym.upper()}_H", "",
        "#include <stdint.h>", '#include "piton_rt.h"', "",
        f"#define {sym.upper()}_NUM_INSTRUCTIONS {len(words)}",
        f"#define {sym.upper()}_NUM_UNIFORMS {len(ck.uniforms)}", "",
        f"extern const uint32_t {sym}_code[{2 * len(words)}];", "",
        "// Pointer arguments are GPU bus addresses (piton_buf_t.bus + offset).",
        "typedef struct {",
    ]
    for n, t in args:
        lines_h.append(f"    {C_TYPES[t]} {n};   // {t}")
    if not args:
        lines_h.append("    int32_t _unused;")
    lines_h += [
        f"}} {sym}_args_t;", "",
        "// Launch gx*gy*gz program instances through the V3D request queue.",
        "// Returns the elapsed time in microseconds.",
        f"uint32_t {sym}_launch(const {sym}_args_t *args, unsigned gx, unsigned gy, unsigned gz);",
        "", "#endif", ""]

    body = [f'#include "{sym}.h"', "", "__attribute__((aligned(8)))",
            f"const uint32_t {sym}_code[{2 * len(words)}] = {{"]
    for w in words:
        body.append(f"    0x{w & 0xFFFFFFFF:08x}, 0x{w >> 32:08x},")
    body += ["};", "",
             "static piton_buf_t code_buf, unif_buf, zero_buf;",
             "static unsigned unif_capacity;", "",
             f"uint32_t {sym}_launch(const {sym}_args_t *args, unsigned gx, unsigned gy, unsigned gz) {{",
             "    unsigned n = gx * gy * gz;",
             "    if (!code_buf.handle) {",
             f"        code_buf = piton_alloc(sizeof({sym}_code));",
             "        volatile uint32_t *c = (volatile uint32_t *)code_buf.cpu;",
             f"        for (unsigned i = 0; i < sizeof({sym}_code) / 4; i++) c[i] = {sym}_code[i];",
             "        zero_buf = piton_alloc(4096);",
             "        volatile uint32_t *z = (volatile uint32_t *)zero_buf.cpu;",
             "        for (unsigned i = 0; i < 1024; i++) z[i] = 0;",
             "    }",
             f"    unsigned need = n * ({max(len(ck.uniforms), 1)} + 1) * 4;   // uniforms + per-program pointers",
             "    if (need > unif_capacity) {",
             "        if (unif_buf.handle) piton_free(&unif_buf);",
             "        unif_buf = piton_alloc(need);",
             "        unif_capacity = unif_buf.size;",
             "    }",
             "    volatile uint32_t *u = (volatile uint32_t *)unif_buf.cpu;",
             f"    uint32_t *unif_ptrs = (uint32_t *)(u + n * {max(len(ck.uniforms), 1)});",
             "    unsigned p = 0;",
             "    for (unsigned z = 0; z < gz; z++)",
             "    for (unsigned y = 0; y < gy; y++)",
             "    for (unsigned x = 0; x < gx; x++, p++) {",
             f"        volatile uint32_t *q = u + p * {max(len(ck.uniforms), 1)};",
             "        uint32_t self = unif_buf.bus + 4 * (uint32_t)(q - u);"]
    for j, (kind, name) in enumerate(ck.uniforms):
        if kind == "arg":
            t = ck.signature[name]
            if t == "fp32":
                body.append(f"        {{ union {{ float f; uint32_t u; }} cv = {{ args->{name} }}; q[{j}] = cv.u; }}")
            else:
                body.append(f"        q[{j}] = (uint32_t)args->{name};")
        elif kind == "pid":
            body.append(f"        q[{j}] = {'xyz'[int(name[3:])]};")
        elif kind == "nprog":
            body.append(f"        q[{j}] = g{'xyz'[int(name[5:])]};")
        elif kind in ("zero", "scratch"):
            off = 0 if kind == "zero" else 2048
            body.append(f"        q[{j}] = zero_buf.bus + {off};")
        elif kind == "self":
            body.append(f"        q[{j}] = self;")
    body += ["        unif_ptrs[p] = self;", "    }",
             "    return piton_launch(code_buf.bus, unif_ptrs, n);", "}", ""]
    return "\n".join(lines_h), "\n".join(body)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Compile a Triton kernel to VideoCore IV QPU code")
    ap.add_argument("path", help="python file containing the @jit kernel")
    ap.add_argument("--kernel-name", "-n", required=True)
    ap.add_argument("--signature", "-s", default="", help="name=type,... for runtime arguments")
    ap.add_argument("--constants", "-c", default="", help="name=value,... constexpr / specialised args")
    ap.add_argument("--out-name", default=None)
    ap.add_argument("--num-stages", type=int, default=2)
    ap.add_argument("--max-grid", default=None,
                    help="largest launch grid, e.g. 4096 or 64,64 (enables program-id range optimisations)")
    ap.add_argument("-o", "--out-dir", default=".")
    ap.add_argument("--dump", choices=["ttir", "ttir_opt", "mir", "mir_alloc", "qasm"], action="append",
                    default=[])
    args = ap.parse_args(argv)
    kernel = _load_kernel(args.path, args.kernel_name)
    sig = _parse_kv(args.signature)
    cons = _parse_kv(args.constants)
    grid = tuple(int(x) for x in args.max_grid.split(",")) if args.max_grid else None
    ck = compiler.compile(kernel, sig, cons, num_stages=args.num_stages, grid=grid)
    name = args.out_name or args.kernel_name
    os.makedirs(args.out_dir, exist_ok=True)
    with open(os.path.join(args.out_dir, name + ".qasm"), "w") as f:
        f.write(ck.asm["qasm"])
    h, c = emit_c(ck, name)
    with open(os.path.join(args.out_dir, name + ".h"), "w") as f:
        f.write(h)
    with open(os.path.join(args.out_dir, name + ".c"), "w") as f:
        f.write(c)
    for d in args.dump:
        print(ck.asm[d])
    msg = f"{name}: {len(ck.program.instrs)} instructions, uniforms: {[n for _, n in ck.uniforms]}"
    if find_vc4asm():
        words, warnings = vc4asm_assemble(ck.asm["qasm"])
        same = words == ck.words
        msg += f"; vc4asm: {'identical binary' if same else 'DIFFERENT binary'}"
        if not same:
            print("warning: vc4asm assembled the .qasm to different bits", file=sys.stderr)
    print(msg)


if __name__ == "__main__":
    main()
