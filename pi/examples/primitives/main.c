// Where the ARM baselines of the current op write, and what to compare them
// against: set once per op by use_ref(), so every baseline gets an error of its
// own rather than only the QPU row being checked.
static const float *cmp_out;
static const float *cmp_ref;
static int cmp_n;

// Copy a reference result somewhere the baselines will not overwrite.
static void snapshot(const float *src, float *dst, int n) {
    for (int i = 0; i < n; i++)
        dst[i] = src[i];
}

static void set_cmp(const float *out, const float *ref, int n) {
    cmp_out = out;
    cmp_ref = ref;
    cmp_n = n;
}

static void no_cmp(void) {
    set_cmp(0, 0, 0);
}

// Run one ARM baseline, time it, and score it against the op's reference.
static row_t *arm_case(const char *op, const char *impl, void (*run)(void),
                       float flop, float bytes, float elems) {
    uint32_t us = best_arm(REPS, run);
    row_t *r = add_row(op, impl, us, last_cycles, flop, bytes, elems, 0);
    if (cmp_ref)
        r->err = rel_err_f(cmp_out, cmp_ref, cmp_n);
    return r;
}

