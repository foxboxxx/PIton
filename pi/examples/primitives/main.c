// The error column is in parts per million, so that a 1e-7 difference stays
// visible instead of rounding to zero.  `bad` is the mismatch count for the
// exact integer ops, where any nonzero value is a failure.
static void print_table(void) {
    printk("\n");
    printk("op          impl         us        cycles     cyc/elem GB/s    GFLOPS  err_ppm     bad\n");
    printk("----------------------------------------------------------------------------------------\n");
    for (int i = 0; i < nrows; i++) {
        row_t *r = &rows[i];
        col_s(r->op, 12);
        col_s(r->impl, 13);
        col_u(r->us, 10);
        col_u(r->cycles, 11);
        col_f(r->per_elem, 2, 9);
        col_f(r->gbps, 3, 8);
        col_f(r->gflops, 3, 8);
        col_f(r->err * 1.0e6f, 3, 12);
        col_u(r->bad, 1);
        printk("\n");
    }
}

// Speedup of the qpu row over every other row of the same op.
static void print_speedups(void) {
    printk("\nSpeedup of the PIton-compiled QPU kernel over each CPU baseline\n");
    printk("(>1x means the QPU is faster; saved is the reduction in run time)\n\n");
    printk("op          baseline     qpu_us    arm_us    speedup  saved\n");
    printk("------------------------------------------------------------\n");
    for (int i = 0; i < nrows; i++) {
        if (rows[i].impl[0] != 'q')
            continue;
        const char *op = rows[i].op;
        uint32_t qus = rows[i].us;
        for (int j = 0; j < nrows; j++) {
            if (j == i || rows[j].op != op)
                continue;
            col_s(op, 12);
            col_s(rows[j].impl, 13);
            col_u(qus, 10);
            col_u(rows[j].us, 10);
            col_f((float)rows[j].us / (float)qus, 2, 8);
            col_f(100.0f * (1.0f - (float)qus / (float)rows[j].us), 1, 6);
            printk("%c\n", '%');
        }
    }
}

static int main_failed;

static void print_results_lines(void) {
    printk("\n");
    for (int i = 0; i < nrows; i++) {
        row_t *r = &rows[i];
        printk("RESULT op=%s impl=%s us=%d cycles=%d cyc_per_elem=%f gbps=%f gflops=%f "
               "err_ppm=%f bad=%d\n", r->op, r->impl, r->us, r->cycles, r->per_elem,
               r->gbps, r->gflops, r->err * 1.0e6f, r->bad);
    }
}

static void check_errors(void) {
    for (int i = 0; i < nrows; i++) {
        row_t *r = &rows[i];
        if (!(r->err <= r->tol) || r->bad != 0) {
            printk("CHECK FAILED %s/%s err_ppm=%f tol_ppm=%f bad=%d\n", r->op, r->impl,
                   r->err * 1.0e6f, r->tol * 1.0e6f, r->bad);
            main_failed = 1;
        }
    }
}

