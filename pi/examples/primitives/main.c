#define MAX_ROWS 64

typedef struct {
    const char *op;
    const char *impl;
    uint32_t us;            // best of REPS
    uint32_t cycles;        // measured ARM cycles (0 for QPU rows: see derived)
    float err;              // max relative difference against the op's reference
    uint32_t bad;           // mismatching elements, for the exact integer ops
    float tol;              // allowed err for this op
    float gflops;           // useful float operations per second (0: not meaningful)
    float gbps;             // bytes moved per second
    float per_elem;         // cycles per element on its own clock
} row_t;

static row_t rows[MAX_ROWS];
static int nrows;
static uint32_t arm_mhz, v3d_mhz;

// Allowed relative error for the op currently being measured.  Set once per op
// (see TOL_* below) and copied into every row, so the check at the end does not
// have to re-derive which op tolerates what.
static float cur_tol;

#define TOL_EXACT  0.0f        // integer division, transpose, row max
#define TOL_FP32   1e-6f       // the same arithmetic in a different order
#define TOL_ACC    1e-5f       // accurate transcendentals and the fp32 matmul
#define TOL_FAST   2e-1f       // the arm-fast rows, which trade accuracy for
                               // speed on purpose: a quadratic for log2 over a
                               // whole octave cannot beat ~1%, and that is the
                               // point of the comparison.  Only loose enough
                               // not to fail; the measured error is reported.

static row_t *add_row(const char *op, const char *impl, uint32_t us, uint32_t cycles,
                      float flop, float bytes, float elems, int on_qpu) {
    row_t *r = &rows[nrows++];
    r->op = op;
    r->impl = impl;
    r->us = us;
    r->cycles = cycles;
    r->err = 0.0f;
    r->bad = 0;
    r->tol = cur_tol;
    r->gflops = us ? flop / (float)us / 1000.0f : 0.0f;
    r->gbps = us ? bytes / (float)us / 1000.0f : 0.0f;
    // Cycles per element on the clock that did the work.  For the QPU this is
    // derived from wall-clock time and the V3D clock, not measured: it counts
    // elapsed cycles of the whole 12-QPU block, not issued instructions.
    uint32_t cyc = on_qpu ? us * v3d_mhz : (cycles ? cycles : us * arm_mhz);
    r->per_elem = elems > 0.0f ? (float)cyc / elems : 0.0f;
    return r;
}

static float absf(float x) { return x < 0.0f ? -x : x; }

// max |x - ref| / max |ref|, NaN-poisoning (a skipped tile must fail)
static float rel_err_f(const volatile float *x, const float *ref, int n) {
    float scale = 0.0f, worst = 0.0f;
    for (int i = 0; i < n; i++)
        if (!(absf(ref[i]) <= scale))
            scale = absf(ref[i]);
    for (int i = 0; i < n; i++) {
        float d = absf(x[i] - ref[i]);
        if (!(d <= worst))
            worst = d;
    }
    if (scale == 0.0f)
        return worst;
    return worst / scale;
}

// Integer results must match exactly: count the mismatches.
static uint32_t count_bad_i(const volatile int32_t *x, const int32_t *ref, int n) {
    uint32_t bad = 0;
    for (int i = 0; i < n; i++)
        if (x[i] != ref[i])
            bad++;
    return bad;
}

// ---------------------------------------------------------------------------
// formatting: libpi's printk has no width or precision specifiers (only
// %d %u %x %s %c %f %b %llx), so columns are padded by hand.
// ---------------------------------------------------------------------------

static int dec_width(uint32_t v) {
    int n = 1;
    while (v >= 10) {
        v /= 10;                 // constant divisor: a multiply, not a helper call
        n++;
    }
    return n;
}

static void pad(int printed, int width) {
    for (int i = printed; i < width; i++)
        printk(" ");
}

static void col_s(const char *s, int width) {
    int n = 0;
    while (s[n])
        n++;
    printk("%s", s);
    pad(n, width);
}

static void col_u(uint32_t v, int width) {
    printk("%d", v);
    pad(dec_width(v), width);
}

// Fixed-point with `dec` decimals, so the column width is predictable.
// Values too large to scale into 32 bits are printed as integers.
static void col_f(float v, int dec, int width) {
    int neg = v < 0.0f;
    if (neg)
        v = -v;
    uint32_t scale = 1;
    for (int i = 0; i < dec; i++)
        scale *= 10;
    if (v > 1.0e6f) {
        int n = neg ? 1 : 0;
        if (neg)
            printk("-");
        uint32_t iv = (uint32_t)v;
        printk("%d", iv);
        pad(n + dec_width(iv), width);
        return;
    }
    uint32_t n = (uint32_t)(v * (float)scale + 0.5f);
    uint32_t ip = n / scale, fp = n - ip * scale;
    int printed = dec_width(ip) + 1 + dec + (neg ? 1 : 0);
    if (neg)
        printk("-");
    printk("%d.", ip);
    for (uint32_t d = scale / 10; d > 1 && fp < d; d /= 10)
        printk("0");                      // leading zeros of the fraction
    if (dec > 0)
        printk("%d", fp);
    pad(printed, width);
}

