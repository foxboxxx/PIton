void notmain(void) {
    piton_init();
    printk("PIton primitive benchmark: %d QPUs, vec=%d, mat=%dx%d, matmul=%d^3\n",
           piton_qpu_count(), VEC, MAT, MAT, MM);

    static const uint32_t ids[4] = {PITON_CLOCK_ARM, PITON_CLOCK_CORE, PITON_CLOCK_V3D,
                                    PITON_CLOCK_SDRAM};
    static const char *cnames[4] = {"arm", "core", "v3d", "sdram"};
    uint32_t mhz_fw[4];
    for (int i = 0; i < 4; i++) {
        mhz_fw[i] = piton_clock_hz(ids[i], 0) / 1000000;
        printk("clock %s: %d MHz (firmware max %d MHz)\n", cnames[i], mhz_fw[i],
               piton_clock_hz(ids[i], 1) / 1000000);
    }
    v3d_mhz = mhz_fw[2];
    uint32_t arm_mem, vc_base, vc_size;
    piton_memory_split(&arm_mem, &vc_base, &vc_size);
    printk("memory: ARM %d MB, GPU %d MB at %x\n", arm_mem >> 20, vc_size >> 20, vc_base);

    // ---- allocate and fill -------------------------------------------------
    g_x = piton_alloc(4 * VEC);
    g_y = piton_alloc(4 * VEC);
    g_xi = piton_alloc(4 * VEC);
    g_yi = piton_alloc(4 * VEC);
    g_q = piton_alloc(4 * VEC);
    g_r = piton_alloc(4 * VEC);
    for (int i = 0; i < 10; i++)
        g_eout[i] = piton_alloc(4 * VEC);
    g_mat = piton_alloc(4 * MAT * MAT);
    g_mout = piton_alloc(4 * MAT * MAT);
    g_rowv = piton_alloc(4 * MAT);
    g_mmA = piton_alloc(4 * MM * MM);
    g_mmB = piton_alloc(4 * MM * MM);
    g_mmC = piton_alloc(4 * MM * MM);

    volatile float *vx = g_x.cpu, *vy = g_y.cpu;
    volatile int32_t *vxi = g_xi.cpu, *vyi = g_yi.cpu;
    uint32_t s1 = 12345, s2 = 67890, s3 = 2468;
    for (int i = 0; i < VEC; i++) {
        float u = piton_lcg_float(&s1);              // [-1, 1)
        a_x[i] = vx[i] = u;
        // log/sqrt/rsqrt/recip need strictly positive inputs well away from 0
        float p = absf(piton_lcg_float(&s2)) * 7.0f + 0.25f;
        a_y[i] = vy[i] = p;
        int32_t num = (int32_t)(piton_lcg_float(&s3) * 1.0e9f);
        uint32_t d = (piton_lcg(&s3) & 0xffffu) + 1u;    // 1..65536, never 0
        int32_t den = (num & 1) ? (int32_t)d : -(int32_t)d;
        a_xi[i] = vxi[i] = num;
        a_yi[i] = vyi[i] = den;
    }
    volatile float *vmat = g_mat.cpu;
    for (int i = 0; i < MAT * MAT; i++)
        a_mat[i] = vmat[i] = piton_lcg_float(&s1) * 4.0f;
    volatile float *vA = g_mmA.cpu, *vB = g_mmB.cpu;
    for (int i = 0; i < MM * MM; i++) {
        mmA[i] = vA[i] = piton_lcg_float(&s1);
        mmB[i] = vB[i] = piton_lcg_float(&s2);
    }
    // NaN-fill every QPU output: a kernel that skips a tile then fails its check
    for (int k = 0; k < 10; k++) {
        volatile uint32_t *o = g_eout[k].cpu;
        for (int i = 0; i < VEC; i++)
            o[i] = 0x7fc00000u;
    }
    {
        volatile uint32_t *o = g_q.cpu, *p = g_r.cpu;
        for (int i = 0; i < VEC; i++) {
            o[i] = 0xdeadbeefu;
            p[i] = 0xdeadbeefu;
        }
        volatile uint32_t *m = g_mout.cpu;
        for (int i = 0; i < MAT * MAT; i++)
            m[i] = 0x7fc00000u;
        volatile uint32_t *v = g_rowv.cpu;
        for (int i = 0; i < MAT; i++)
            v[i] = 0x7fc00000u;
        volatile uint32_t *c = g_mmC.cpu;
        for (int i = 0; i < MM * MM; i++)
            c[i] = 0x7fc00000u;
    }

    // ---- QPU phase (before the ARM caches are enabled) ---------------------
    const float velems = (float)VEC;
    const float melems = (float)MAT * (float)MAT;

    c_copy.x_ptr = g_x.bus;  c_copy.out_ptr = g_eout[0].bus;  c_copy.n = VEC;
    uint32_t t_copy = QPU_BEST(op_copy, &c_copy, OP_COPY_GRID);

    c_add.x_ptr = g_x.bus;  c_add.y_ptr = g_y.bus;
    c_add.output_ptr = g_eout[1].bus;  c_add.n_elements = VEC;
    uint32_t t_add = QPU_BEST(op_add, &c_add, OP_ADD_GRID);

    c_mul.x_ptr = g_x.bus;  c_mul.y_ptr = g_y.bus;
    c_mul.out_ptr = g_eout[2].bus;  c_mul.n = VEC;
    uint32_t t_mul = QPU_BEST(op_mul, &c_mul, OP_MUL_GRID);

    c_fma.x_ptr = g_x.bus;  c_fma.y_ptr = g_y.bus;  c_fma.out_ptr = g_eout[3].bus;
    c_fma.n = VEC;  c_fma.alpha = ALPHA;
    uint32_t t_fma = QPU_BEST(op_fma, &c_fma, OP_FMA_GRID);

    c_relu.x_ptr = g_x.bus;  c_relu.out_ptr = g_eout[4].bus;
    c_relu.n = VEC;  c_relu.alpha = ALPHA;
    uint32_t t_relu = QPU_BEST(op_relu, &c_relu, OP_RELU_GRID);

    c_exp.x_ptr = g_x.bus;  c_exp.out_ptr = g_eout[5].bus;  c_exp.n = VEC;
    uint32_t t_exp = QPU_BEST(op_exp, &c_exp, OP_EXP_GRID);

    c_log.x_ptr = g_y.bus;  c_log.out_ptr = g_eout[6].bus;  c_log.n = VEC;
    uint32_t t_log = QPU_BEST(op_log, &c_log, OP_LOG_GRID);

    c_sqrt.x_ptr = g_y.bus;  c_sqrt.out_ptr = g_eout[7].bus;  c_sqrt.n = VEC;
    uint32_t t_sqrt = QPU_BEST(op_sqrt, &c_sqrt, OP_SQRT_GRID);

    c_rsqrt.x_ptr = g_y.bus;  c_rsqrt.out_ptr = g_eout[8].bus;  c_rsqrt.n = VEC;
    uint32_t t_rsqrt = QPU_BEST(op_rsqrt, &c_rsqrt, OP_RSQRT_GRID);

    c_recip.x_ptr = g_y.bus;  c_recip.out_ptr = g_eout[9].bus;  c_recip.n = VEC;
    uint32_t t_recip = QPU_BEST(op_recip, &c_recip, OP_RECIP_GRID);

    c_idiv.x_ptr = g_xi.bus;  c_idiv.y_ptr = g_yi.bus;
    c_idiv.q_ptr = g_q.bus;   c_idiv.r_ptr = g_r.bus;  c_idiv.n = VEC;
    uint32_t t_idiv = QPU_BEST(op_idiv, &c_idiv, OP_IDIV_GRID);

    c_rowsum.x_ptr = g_mat.bus;  c_rowsum.out_ptr = g_rowv.bus;
    c_rowsum.n_cols = MAT;  c_rowsum.stride = MAT;
    uint32_t t_rowsum = QPU_BEST(op_rowsum, &c_rowsum, OP_ROWSUM_GRID);
    static float qpu_rowsum[MAT];
    {
        volatile float *v = g_rowv.cpu;
        for (int i = 0; i < MAT; i++)
            qpu_rowsum[i] = v[i];              // the rowmax kernel reuses this buffer
    }

    c_rowmax.x_ptr = g_mat.bus;  c_rowmax.out_ptr = g_rowv.bus;
    c_rowmax.n_cols = MAT;  c_rowmax.stride = MAT;
    uint32_t t_rowmax = QPU_BEST(op_rowmax, &c_rowmax, OP_ROWMAX_GRID);
    static float qpu_rowmax[MAT];
    {
        volatile float *v = g_rowv.cpu;
        for (int i = 0; i < MAT; i++)
            qpu_rowmax[i] = v[i];
    }

    c_transpose.x_ptr = g_mat.bus;  c_transpose.out_ptr = g_mout.bus;
    c_transpose.n_rows = MAT;  c_transpose.n_cols = MAT;
    c_transpose.stride_x = MAT;  c_transpose.stride_out = MAT;
    uint32_t t_tr = QPU_BEST(op_transpose, &c_transpose, OP_TRANSPOSE_GRID);
    static float qpu_tr[MAT * MAT];
    {
        volatile float *v = g_mout.cpu;
        for (int i = 0; i < MAT * MAT; i++)
            qpu_tr[i] = v[i];                  // the softmax kernel reuses this buffer
    }

    c_softmax.input_ptr = g_mat.bus;  c_softmax.output_ptr = g_mout.bus;
    c_softmax.input_row_stride = MAT;  c_softmax.output_row_stride = MAT;
    c_softmax.n_cols = MAT;
    uint32_t t_sm = QPU_BEST(op_softmax, &c_softmax, OP_SOFTMAX_GRID);

    c_matmul.a_ptr = g_mmA.bus;  c_matmul.b_ptr = g_mmB.bus;  c_matmul.c_ptr = g_mmC.bus;
    c_matmul.M = MM;  c_matmul.N = MM;
    c_matmul.stride_am = MM;  c_matmul.stride_bk = MM;  c_matmul.stride_cm = MM;
    uint32_t t_mm = QPU_BEST(op_matmul, &c_matmul, OP_MATMUL_GRID);

    printk("QPU phase done; instruction counts: copy=%d add=%d exp=%d idiv=%d matmul=%d\n",
           OP_COPY_INSTRS, OP_ADD_INSTRS, OP_EXP_INSTRS, OP_IDIV_INSTRS, OP_MATMUL_INSTRS);

    // ---- ARM phase ---------------------------------------------------------
    arm_caches_on();
    arm_mhz = arm_clock_mhz();

    // Byte and flop counts per op: what the kernel must move / compute.
    const float b3 = 12.0f * velems;     // two loads + one store
    const float b2 = 8.0f * velems;      // one load + one store
    const float bmat2 = 8.0f * melems;                        // read and write the matrix
    // The row reductions read the whole matrix but write one value per row.
    const float bmat_red = 4.0f * melems + 4.0f * (float)MAT;
    row_t *q;

    // -- copy
    cur_tol = TOL_FP32;
    q = add_row("copy", "qpu", t_copy, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[0].cpu, a_x, VEC);
    set_cmp(a_out, a_x, VEC);
    arm_case("copy", "arm-naive", r_copy_naive, 0.0f, b2, velems);
    arm_case("copy", "arm-unroll", r_copy_unroll, 0.0f, b2, velems);
    arm_case("copy", "arm-vfp", r_copy_vfp, 0.0f, b2, velems);

    // -- add (reference: naive, which is exact for fp32 addition)
    cur_tol = TOL_FP32;
    ref_add_naive(a_x, a_y, a_out, VEC);
    q = add_row("add", "qpu", t_add, 0, velems, b3, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[1].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("add", "arm-naive", r_add_naive, velems, b3, velems);
    arm_case("add", "arm-unroll", r_add_unroll, velems, b3, velems);
    arm_case("add", "arm-vfp", r_add_vfp, velems, b3, velems);

    // -- mul
    cur_tol = TOL_FP32;
    ref_mul_naive(a_x, a_y, a_out, VEC);
    q = add_row("mul", "qpu", t_mul, 0, velems, b3, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[2].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("mul", "arm-naive", r_mul_naive, velems, b3, velems);
    arm_case("mul", "arm-unroll", r_mul_unroll, velems, b3, velems);
    arm_case("mul", "arm-vfp", r_mul_vfp, velems, b3, velems);

    // -- fma (two flops per element)
    cur_tol = TOL_FP32;
    ref_fma_naive(a_x, a_y, a_out, VEC, ALPHA);
    q = add_row("fma", "qpu", t_fma, 0, 2.0f * velems, b3, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[3].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("fma", "arm-naive", r_fma_naive, 2.0f * velems, b3, velems);
    arm_case("fma", "arm-unroll", r_fma_unroll, 2.0f * velems, b3, velems);
    arm_case("fma", "arm-vfp", r_fma_vfp, 2.0f * velems, b3, velems);

    // -- relu (compare + select + multiply; no VFP vector form)
    cur_tol = TOL_FP32;
    ref_relu_naive(a_x, a_out, VEC, ALPHA);
    q = add_row("relu", "qpu", t_relu, 0, 2.0f * velems, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[4].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("relu", "arm-naive", r_relu_naive, 2.0f * velems, b2, velems);
    arm_case("relu", "arm-unroll", r_relu_unroll, 2.0f * velems, b2, velems);

    // -- exp (reference: the accurate CPU version).  PIton's exp and log turn
    //    out to be accurate to ~0.2 ppm, not special-function-unit precision.
    cur_tol = TOL_ACC;
    ref_map(a_x, a_out, VEC, ref_exp_acc);
    q = add_row("exp", "qpu", t_exp, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[5].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("exp", "arm-naive", r_exp_acc, 0.0f, b2, velems);
    arm_case("exp", "arm-unroll", r_exp_acc_u, 0.0f, b2, velems);
    cur_tol = TOL_FAST;
    arm_case("exp", "arm-fast", r_exp_fast, 0.0f, b2, velems);

    // -- log
    cur_tol = TOL_ACC;
    ref_map(a_y, a_out, VEC, ref_log_acc);
    q = add_row("log", "qpu", t_log, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[6].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("log", "arm-naive", r_log_acc, 0.0f, b2, velems);
    arm_case("log", "arm-unroll", r_log_acc_u, 0.0f, b2, velems);
    cur_tol = TOL_FAST;
    arm_case("log", "arm-fast", r_log_fast, 0.0f, b2, velems);

    // -- sqrt
    cur_tol = TOL_ACC;
    ref_map(a_y, a_out, VEC, ref_sqrt_vfp);
    q = add_row("sqrt", "qpu", t_sqrt, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[7].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("sqrt", "arm-vfp", r_sqrt_vfp, 0.0f, b2, velems);
    arm_case("sqrt", "arm-naive", r_sqrt_newton, 0.0f, b2, velems);
    cur_tol = TOL_FAST;
    arm_case("sqrt", "arm-fast", r_sqrt_fast, 0.0f, b2, velems);

    // -- rsqrt
    cur_tol = TOL_ACC;
    ref_map(a_y, a_out, VEC, ref_rsqrt_vfp);
    q = add_row("rsqrt", "qpu", t_rsqrt, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[8].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("rsqrt", "arm-vfp", r_rsqrt_vfp, 0.0f, b2, velems);
    arm_case("rsqrt", "arm-naive", r_rsqrt_newton, 0.0f, b2, velems);
    cur_tol = TOL_FAST;
    arm_case("rsqrt", "arm-fast", r_rsqrt_fast, 0.0f, b2, velems);

    // -- recip (naive C `1.0f/x` is already a hardware vdiv, so there is no
    //    separate arm-vfp row)
    cur_tol = TOL_ACC;
    ref_map(a_y, a_out, VEC, ref_recip_vdiv);
    q = add_row("recip", "qpu", t_recip, 0, 0.0f, b2, velems, 1);
    q->err = rel_err_f((volatile float *)g_eout[9].cpu, a_out, VEC);
    snapshot(a_out, ref_vec, VEC);
    set_cmp(a_out, ref_vec, VEC);
    arm_case("recip", "arm-naive", r_recip_vdiv, 0.0f, b2, velems);
    cur_tol = TOL_FAST;
    arm_case("recip", "arm-fast", r_recip_fast, 0.0f, b2, velems);

    // -- idiv (exact: two integer outputs, 16 bytes per element)
    cur_tol = TOL_EXACT;
    ref_idivmod_shift(a_xi, a_yi, a_q, a_r, VEC);
    q = add_row("idiv", "qpu", t_idiv, 0, 0.0f, 16.0f * velems, velems, 1);
    q->bad = count_bad_i((volatile int32_t *)g_q.cpu, a_q, VEC)
           + count_bad_i((volatile int32_t *)g_r.cpu, a_r, VEC);
    no_cmp();
    arm_case("idiv", "arm-naive", r_idiv_shift, 0.0f, 16.0f * velems, velems);
    {
        // the float-estimate version must agree with shift-subtract exactly
        static int32_t keep_q[VEC], keep_r[VEC];
        for (int i = 0; i < VEC; i++) {
            keep_q[i] = a_q[i];
            keep_r[i] = a_r[i];
        }
        row_t *e = arm_case("idiv", "arm-fast", r_idiv_est, 0.0f, 16.0f * velems, velems);
        e->bad = count_bad_i(a_q, keep_q, VEC) + count_bad_i(a_r, keep_r, VEC);
        for (int i = 0; i < VEC; i++) {
            a_q[i] = keep_q[i];
            a_r[i] = keep_r[i];
        }
    }

    // -- row sum (reference: naive; the others differ in summation order)
    cur_tol = TOL_FP32;
    ref_rowsum_naive(a_mat, a_rowv, MAT, MAT);
    q = add_row("rowsum", "qpu", t_rowsum, 0, melems, bmat_red, melems, 1);
    q->err = rel_err_f(qpu_rowsum, a_rowv, MAT);
    snapshot(a_rowv, ref_row, MAT);
    set_cmp(a_rowv, ref_row, MAT);
    arm_case("rowsum", "arm-naive", r_rowsum_naive, melems, bmat_red, melems);
    arm_case("rowsum", "arm-unroll", r_rowsum_unroll, melems, bmat_red, melems);
    arm_case("rowsum", "arm-vfp", r_rowsum_vfp, melems, bmat_red, melems);

    // -- row max (exact)
    cur_tol = TOL_EXACT;
    ref_rowmax_naive(a_mat, a_rowv, MAT, MAT);
    q = add_row("rowmax", "qpu", t_rowmax, 0, 0.0f, bmat_red, melems, 1);
    q->err = rel_err_f(qpu_rowmax, a_rowv, MAT);
    snapshot(a_rowv, ref_row, MAT);
    set_cmp(a_rowv, ref_row, MAT);
    arm_case("rowmax", "arm-naive", r_rowmax_naive, 0.0f, bmat_red, melems);
    arm_case("rowmax", "arm-unroll", r_rowmax_unroll, 0.0f, bmat_red, melems);

    // -- transpose (exact)
    cur_tol = TOL_EXACT;
    ref_transpose_naive(a_mat, a_mout, MAT, MAT);
    q = add_row("transpose", "qpu", t_tr, 0, 0.0f, bmat2, melems, 1);
    q->err = rel_err_f(qpu_tr, a_mout, MAT * MAT);
    snapshot(a_mout, ref_mat, MAT * MAT);
    set_cmp(a_mout, ref_mat, MAT * MAT);
    arm_case("transpose", "arm-naive", r_tr_naive, 0.0f, bmat2, melems);
    arm_case("transpose", "arm-blocked", r_tr_blocked, 0.0f, bmat2, melems);

    // -- softmax (max + exp + sum + divide over each row)
    cur_tol = TOL_ACC;
    ref_softmax_acc(a_mat, a_mout, MAT, MAT);
    q = add_row("softmax", "qpu", t_sm, 0, 4.0f * melems, bmat2, melems, 1);
    q->err = rel_err_f((volatile float *)g_mout.cpu, a_mout, MAT * MAT);
    snapshot(a_mout, ref_mat, MAT * MAT);
    set_cmp(a_mout, ref_mat, MAT * MAT);
    arm_case("softmax", "arm-naive", r_sm_acc, 4.0f * melems, bmat2, melems);
    cur_tol = TOL_FAST;
    arm_case("softmax", "arm-fast", r_sm_fast, 4.0f * melems, bmat2, melems);

    // -- matmul (reference: blocked C, as in pi/examples/matmul)
    cur_tol = TOL_ACC;
    const float mmflop = 2.0f * (float)MM * (float)MM * (float)MM;
    const float mmelems = (float)MM * (float)MM;
    arm_matmul_blocked(mmA, mmB, mmC, MM, MM, MM, pack_a, pack_b, 0);
    q = add_row("matmul", "qpu", t_mm, 0, mmflop, 12.0f * mmelems, mmelems, 1);
    q->err = rel_err_f((volatile float *)g_mmC.cpu, mmC, MM * MM);
    snapshot(mmC, ref_mat, MM * MM);
    set_cmp(mmC, ref_mat, MM * MM);
    arm_case("matmul", "arm-naive", r_mm_naive, mmflop, 12.0f * mmelems, mmelems);
    arm_case("matmul", "arm-blocked", r_mm_blocked, mmflop, 12.0f * mmelems, mmelems);
    arm_case("matmul", "arm-vfp", r_mm_vfp, mmflop, 12.0f * mmelems, mmelems);

    arm_caches_off();

    // ---- report ------------------------------------------------------------
    printk("\nARM clock %d MHz (PMU), V3D %d MHz; ARM VFP peak %f GFLOPS, "
           "12-QPU issue ceiling %f GFLOPS\n", arm_mhz, v3d_mhz,
           2.0f * (float)arm_mhz / 1000.0f, 2.0f * 16.0f * 12.0f * (float)v3d_mhz / 1000.0f);
    printk("cyc/elem for qpu rows is derived (wall time x V3D clock), not measured\n");
    print_table();
    print_speedups();
    print_results_lines();
    check_errors();
    printk(main_failed ? "CHECK FAILED\n" : "CHECK OK\n");
    printk("PITON_DONE\n");
}
