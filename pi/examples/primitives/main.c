// Per-primitive benchmark: every Triton operation PIton supports, compiled to
// VideoCore IV machine code and run on all 12 QPUs, against every CPU baseline
// we can write for the same operation on the ARM1176 of the same board.
//
// One boot measures, for each primitive, the QPU kernel and two to five
// labelled CPU implementations (see arm_ref.h for what the labels mean), checks
// every implementation against a designated reference, and prints a table with
// time, cycles, throughput and the QPU's speedup over each baseline.
//
// All GPU and mailbox work happens before the ARM caches are enabled, as in
// pi/examples/matmul: the runtime's mailbox buffer lives in ARM memory.
