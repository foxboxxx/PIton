static uint32_t last_cycles;

// Best-of-REPS wall time; last_cycles holds the ARM cycles of the best run.
static uint32_t best_arm(int reps, void (*run)(void)) {
    uint32_t best = ~0u, best_cyc = 0;
    for (int i = 0; i < reps; i++) {
        uint32_t c0 = arm_cycles(), t0 = timer_get_usec();
        run();
        uint32_t t = timer_get_usec() - t0, c = arm_cycles() - c0;
        if (t < best) {
            best = t;
            best_cyc = c;
        }
    }
    last_cycles = best_cyc;
    return best ? best : 1;      // never report 0 us
}

