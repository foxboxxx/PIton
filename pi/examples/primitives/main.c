// Best-of-REPS of the whole launch (uniform writes, cache flush, queue, wait).
#define QPU_BEST(sym, argp, grid)                                   \
    ({                                                              \
        uint32_t _best = ~0u;                                       \
        for (int _i = 0; _i < REPS; _i++) {                         \
            uint32_t _t0 = timer_get_usec();                        \
            sym##_launch(argp, (grid), 1, 1);                       \
            uint32_t _t = timer_get_usec() - _t0;                   \
            if (_t < _best) _best = _t;                             \
        }                                                           \
        _best ? _best : 1;                                          \
    })

