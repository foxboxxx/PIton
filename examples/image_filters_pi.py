"""Image filters (Gaussian blur, Sobel edges) on the attached bare-metal Pi.

    .venv/bin/python examples/image_filters_pi.py               # build, check, boot, verify, save
    .venv/bin/python examples/image_filters_pi.py --dry-run     # everything except the boot
    .venv/bin/python examples/image_filters_pi.py --build-only  # kernels and firmware only
    .venv/bin/python examples/image_filters_pi.py --dump-images # also read the Pi's images back

Every filter of examples/image_filters.py is compiled for a 640 x 480 image
and linked into one bare-metal program (pi/examples/image_filters) with plain
C versions of the same filters for the ARM. The board generates the test scene
itself (scene.h), runs every QPU filter on a small ragged image and on the full
image, times them, then times the ARM versions with the L1 caches on and
compares their output with the QPU's.

Checks: the Pi prints a hash of every output row; each must equal the host
model (numpy, exact for these integer images, plus PIton's own sqrt from the
strict emulator), which the strict emulator reproduces bit for bit at the
check size before the boot. Filters with the same output must agree bit for
bit on the board; the ARM blurs must match the QPU's bits and the ARM Sobel
images (VFP vsqrt) must be within IF_MAX_ULP. Timings are the whole launch
call (uniforms, cache clears, queueing) for the QPU and the whole function for
the ARM, median of --repeats.

Writes benchmarks/results/image_filters-pi-<date>.{json,log} and
docs/images/image_filters-*.png (the model's images: the Pi's are the same
bits; with --dump-images also image_filters-pi-*.png from the board).
"""

