def mix32(h: np.ndarray) -> np.ndarray:
    h = h.astype(np.uint32)
    h ^= h >> np.uint32(16)
    h *= np.uint32(0x85EBCA6B)
    h ^= h >> np.uint32(13)
    h *= np.uint32(0xC2B2AE35)
    h ^= h >> np.uint32(16)
    return h


def row_hashes(img: np.ndarray) -> np.ndarray:
    """The firmware's row_hash() of every row of a float32 image."""
    words = np.ascontiguousarray(img, np.float32).view(np.uint32)
    keys = words ^ (np.arange(words.shape[1], dtype=np.uint32) * np.uint32(0x9E3779B9))
    return (mix32(keys).astype(np.uint64).sum(axis=1) & 0xFFFFFFFF).astype(np.uint32)


def image_hash(img: np.ndarray) -> int:
    return int(row_hashes(img).astype(np.uint64).sum() & 0xFFFFFFFF)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def c_scene(params: dict) -> str:
    return "{ " + ", ".join(str(params[k]) for k in ("w", "h", "sx", "sy", "gx", "gy")) + " }"


def symbol(name: str, launch: int) -> str:
    return f"if_{name}_{launch}"


def kernels_header(names: list, compiled: dict) -> str:
    """if_kernels.h: the generated launchers, one run wrapper per filter, and
    the table main.c walks."""
    lines = ["// Generated by examples/image_filters_pi.py.", "#pragma once", "#include <stdint.h>"]
    lines += [f'#include "{symbol(n, i)}.h"' for n in names for i in range(len(compiled[n]))]
    lines += ["",
              "typedef void (*if_run_t)(uint32_t src, uint32_t dst, uint32_t tmp, int32_t h, int32_t w);",
              "typedef struct { const char *name, *output; int first; if_run_t run; } if_filter_t;", ""]
    for n in names:
        lines.append(f"static void if_run_{n}(uint32_t src, uint32_t dst, uint32_t tmp, int32_t h, int32_t w) {{")
        launches = compiled[n]
        for i, (ck, constants) in enumerate(launches):
            s = symbol(n, i)
            into = "dst" if i == len(launches) - 1 else "tmp"
            frm = "src" if i == 0 else "tmp"
            bw, rows = constants["BLOCK_W"], constants["ROWS"]
            lines += [f"    {s}_args_t a{i} = {{ .src_ptr = {frm}, .dst_ptr = {into}, .H = h, .W = w,",
                      f"        .src_stride = w, .dst_stride = w }};",
                      f"    {s}_launch(&a{i}, ((unsigned)w + {bw - 1}u) / {bw}u, "
                      f"((unsigned)h + {rows - 1}u) / {rows}u, 1);"]
        lines += ["}", ""]
    lines.append(f"#define IF_NUM_FILTERS {len(names)}")
    lines.append(f"#define IF_NUM_OUTPUTS {len(OUTPUTS)}")
    lines.append("static const char *const if_outputs[IF_NUM_OUTPUTS] = {"
                 + ", ".join(f'"{o}"' for o in OUTPUTS) + "};")
    lines.append("static const int if_dump_outputs[IF_NUM_OUTPUTS] = {"
                 + ", ".join("1" if o in PI_DUMP else "0" for o in OUTPUTS) + "};")
    lines.append("static const float if_dump_scale[IF_NUM_OUTPUTS] = {"
                 + ", ".join(float(np.float32(filters.EDGE_SCALE if "sobel" in o else 1.0)).hex() + "f"
                             for o in OUTPUTS) + "};")
    seen = set()
    lines.append("static const if_filter_t if_filters[IF_NUM_FILTERS] = {")
    for n in names:
        out = filters.OUTPUTS[n]
        lines.append(f'    {{ "{n}", "{out}", {int(out not in seen)}, if_run_{n} }},')
        seen.add(out)
    lines.append("};")
    return "\n".join(lines) + "\n"


def build_firmware(args, names: list, compiled: dict | None = None) -> tuple[Path, dict, dict]:
    """Compile the filters (unless `compiled` has them), generate the headers,
    build main.bin (no boot)."""
    build = args.build_dir.resolve()
    build.mkdir(parents=True, exist_ok=True)
    for old in build.glob("if_*.[ch]"):
        old.unlink()
    H, W = args.height, args.width
    compiled, kernels = dict(compiled or {}), []
    for n in names:
        if n not in compiled:
            compiled[n] = filters.compile_filter(n, H, W)
        for i, (ck, constants) in enumerate(compiled[n]):
            header, source = emit_c(ck, symbol(n, i))
            (build / f"{symbol(n, i)}.h").write_text(header)
            (build / f"{symbol(n, i)}.c").write_text(source)
            (build / f"{symbol(n, i)}.qasm").write_text(ck.asm["qasm"])
            grid = filters.grid_for(H, W, constants)
            kernels.append(dict(filter=n, launch=i, kernel=ck.name, instructions=len(ck.program.instrs),
                                programs=grid[0] * grid[1],
                                constants={k: v for k, v in constants.items()},
                                code_sha256=hashlib.sha256(b"".join(
                                    int(w).to_bytes(8, "little") for w in ck.words)).hexdigest()))
        print(f"  {n:20s} " + " + ".join(f"{len(ck.program.instrs)} instructions" for ck, _ in compiled[n])
              + f", {filters.LOADS[n]} loads/pixel, tiles {filters.TILES[n]}", flush=True)
    (build / "if_kernels.h").write_text(kernels_header(names, compiled))
    (build / "kernels.mk").write_text("IF_KERNEL_SRC := " + " ".join(
        f"{symbol(n, i)}.c" for n in names for i in range(len(compiled[n]))) + "\n")
    ch, cw = args.check_size
    config = ["// Generated by examples/image_filters_pi.py.", "#pragma once",
              f"#define IF_W {W}", f"#define IF_H {H}", f"#define IF_REPEATS {args.repeats}",
              f"#define IF_MAX_ULP {MAX_ULP}", f"#define IF_DUMP {int(args.dump_images)}",
              f"#define IF_SCENE_FULL {c_scene(filters.scene_params(H, W))}",
              f"#define IF_SCENE_CHECK {c_scene(filters.scene_params(ch, cw))}"]
    (build / "if_config.h").write_text("\n".join(config) + "\n")
    sources = [ROOT / "pi/examples/image_filters" / s for s in SOURCES]
    sources += [ROOT / "pi/runtime" / s for s in ("piton_rt.c", "piton_rt.h")]
    sources += [ROOT / "pi/examples/matmul" / s for s in ("arm_sgemm.c", "arm_sgemm.h", "arm_kernel_vfp.S")]
    for source in sources:
        shutil.copyfile(source, build / source.name)
    course_root = libpi_root()
    if course_root is None:
        raise SystemExit("Set CS240LX_2025_PATH to the course repository containing libpi")
    env = {**os.environ, "CS240LX_2025_PATH": course_root}
    built = subprocess.run(["make", "-s", "RUN=0"], cwd=build, env=env, capture_output=True, text=True)
    (build / "build.log").write_text(built.stdout + built.stderr)
    if built.returncode:
        raise SystemExit(f"Firmware build failed (see {build / 'build.log'}):\n{built.stdout}\n{built.stderr}")
    binary = build / "main.bin"
    tracked = sources + [ROOT / "examples/image_filters.py", ROOT / "examples/image_filters_pi.py"]
    manifest = dict(width=W, height=H, check_size=[cw, ch], repeats=args.repeats, filters=names,
                    kernels=kernels, tiles={n: list(filters.TILES[n]) for n in names},
                    loads_per_pixel={n: filters.LOADS[n] for n in names},
                    firmware_bytes=binary.stat().st_size, firmware_sha256=sha256(binary),
                    source_sha256={str(p.relative_to(ROOT)): sha256(p) for p in tracked},
                    environment={k: os.environ[k] for k in sorted(os.environ) if k.startswith("PITON_")})
    return binary, manifest, compiled


def host_model(args) -> dict:
    """Exact expected outputs at both sizes: {"check" | "full": {"scene": img, output: img}}."""
    sizes = {"check": tuple(args.check_size), "full": (args.height, args.width)}
    model = {}
    for size, (H, W) in sizes.items():
        img = filters.make_scene(H, W)
        model[size] = {"scene": img, **{o: filters.model(o, img) for o in OUTPUTS}}
    return model


def emulator_check(names: list, compiled: dict, model: dict) -> None:
    """Every compiled filter on the strict emulator at the check size, against the model."""
    img = model["check"]["scene"]
    for n in names:
        t = time.monotonic()
        got = filters.run_filter(n, img, compiled=compiled[n])
        want = model["check"][filters.OUTPUTS[n]]
        if not np.array_equal(got.view(np.uint32), want.view(np.uint32)):
            bad = np.argwhere(got.view(np.uint32) != want.view(np.uint32))
            raise SystemExit(f"emulator and model differ for {n} at {len(bad)} pixels, first {bad[0].tolist()}")
        print(f"  {n:20s} emulator = model, bit for bit ({time.monotonic() - t:.1f} s)", flush=True)


def montage(tiles: list, gap: int = 8) -> np.ndarray:
    """Four images in a 2 x 2 grid at half size (2 x 2 means), on a white background."""
    halves = [t.reshape(t.shape[0] // 2, 2, t.shape[1] // 2, 2).mean(axis=(1, 3)).round().astype(np.uint8)
              for t in (t[:t.shape[0] // 2 * 2, :t.shape[1] // 2 * 2] for t in tiles)]
    h, w = halves[0].shape
    out = np.full((2 * h + gap, 2 * w + gap), 255, np.uint8)
    for i, t in enumerate(halves):
        y, x = (i // 2) * (h + gap), (i % 2) * (w + gap)
        out[y:y + h, x:x + w] = t
    return out


def detail(tiles: list, box=(8, 24, 104, 152), zoom: int = 3, gap: int = 6) -> np.ndarray:
    """The same crop (y0, x0, y1, x1) of each image, enlarged `zoom` times, side by side."""
    y0, x0, y1, x1 = box
    crops = [np.kron(t[y0:y1, x0:x1], np.ones((zoom, zoom), np.uint8)) for t in tiles]
    h, w = crops[0].shape
    out = np.full((h, len(crops) * (w + gap) - gap), 255, np.uint8)
    for i, c in enumerate(crops):
        out[:, i * (w + gap):i * (w + gap) + w] = c
    return out


def write_model_images(model: dict, directory: Path) -> list:
    full = model["full"]
    paths = [(directory / "image_filters-input.png", filters.to_u8(full["scene"]))]
    paths += [(directory / f"image_filters-{o}.png", filters.display(o, full[o])) for o in DUMP_OUTPUTS]
    paths.append((directory / "image_filters-montage.png", montage([p for _, p in paths])))
    paths.append((directory / "image_filters-detail.png", detail([p for _, p in paths[:4]])))
    for path, pixels in paths:
        filters.write_png(str(path), pixels)
    return [p for p, _ in paths]


# -- the log ------------------------------------------------------------------

def records(log: str, tag: str) -> list[dict]:
    return [dict(re.findall(r"(\w+)=(\S+)", line)) for line in log.splitlines()
            if line.startswith(tag + " ")]


def parse_blocks(log: str, start: str, end: str) -> list[tuple[dict, list[str]]]:
    """[(fields of the start line, the lines up to `end`)]; raises on a cut-off block."""
    blocks, lines, i = [], log.splitlines(), 0
    while i < len(lines):
        if lines[i].startswith(start + " "):
            fields = dict(re.findall(r"(\w+)=(\S+)", lines[i]))
            body = []
            i += 1
            while i < len(lines) and lines[i].strip() != end:
                if lines[i].startswith(start + " "):
                    break
                body.append(lines[i])
                i += 1
            if i == len(lines) or lines[i].strip() != end:
                raise ValueError(f"{start} block for {fields} is cut off")
            blocks.append((fields, body))
        i += 1
    return blocks


def parse_log(log: str, names: list, model: dict, repeats: int, dump: bool = False) -> dict:
    """Check everything the firmware printed against the model; raise ValueError on any failure."""
    errors = []
    if not re.search(r"^PITON_DONE\s*$", log, re.MULTILINE):
        raise ValueError("the Pi did not finish (no PITON_DONE)")
    for size in ("check", "full"):
        scene = [r for r in records(log, "IF_SCENE") if r.get("size") == size]
        want = image_hash(model[size]["scene"])
        if len(scene) != 1 or int(scene[0]["hash"]) != want:
            errors.append(f"{size} scene: the board's scene.h image differs from make_scene() "
                          f"(hash {scene[0]['hash'] if scene else 'missing'}, expected {want})")
    rows = {}
    for fields, body in parse_blocks(log, "IF_ROWS", "IF_ROWS_END"):
        key = (fields["filter"], fields["size"])
        if key in rows:
            errors.append(f"duplicate row hashes for {key}")
        try:
            rows[key] = np.array([int(v, 16) for line in body for v in line.split()], dtype=np.uint64)
        except ValueError:
            errors.append(f"garbled row hashes for {key}")
    checked_rows = 0
    for n in names:
        for size in ("check", "full"):
            want = row_hashes(model[size][filters.OUTPUTS[n]]).astype(np.uint64)
            got = rows.get((n, size))
            if got is None or len(got) != len(want):
                errors.append(f"{n} {size}: expected {len(want)} row hashes, got "
                              f"{'none' if got is None else len(got)}")
                continue
            bad = np.nonzero(got != want)[0]
            checked_rows += len(want)
            if len(bad):
                errors.append(f"{n} {size}: {len(bad)} of {len(want)} rows differ from the model "
                              f"(first rows {bad[:8].tolist()})")
    for r in records(log, "IF_SAME"):
        if int(r["mismatches"]):
            errors.append(f"{r['filter']} differs from the first {r['output']} filter in "
                          f"{r['mismatches']} pixels on the board")
    stable = {r["filter"]: r["same"] for r in records(log, "IF_STABLE")}
    for n in names:
        if stable.get(n) != "1":
            errors.append(f"{n}: output {'changed during' if n in stable else 'not rehashed after'} the timed runs")
    times = {}
    for r in records(log, "IF_TIME"):
        us = int(r["us"])
        if us <= 0:
            errors.append(f"non-positive time {r}")
        times.setdefault((r["impl"], r["name"]), []).append(us)
    arm_checks = {}
    for r in records(log, "IF_CHECK"):
        arm_checks[r["arm"]] = r
        if r.get("skipped") == "1":
            continue
        output, _ = ARM_IMPLS[r["arm"]]
        exact_needed = output.startswith("blur") and output != "blur_sobel"
        if int(r["failures"]) or (exact_needed and r["exact"] != r["checked"]):
            errors.append(f"{r['arm']} vs the QPU: {r['failures']} failures, {r['exact']}/{r['checked']} "
                          f"exact, max {r['max_ulp']} ulp")
    expected_arm = [a for a, (o, _) in ARM_IMPLS.items()]
    for a in expected_arm:
        if a not in arm_checks:
            errors.append(f"no comparison for {a}")
    timings = []
    for impl, name in ([("qpu", n) for n in names] + [("qpu_icache", n) for n in names]
                       + [("arm", a) for a in expected_arm]):
        samples = times.get((impl, name), [])
        if len(samples) != repeats:
            errors.append(f"expected {repeats} timings for {impl} {name}, got {len(samples)}")
            continue
        output = ARM_IMPLS[name][0] if impl == "arm" else filters.OUTPUTS[name]
        median = statistics.median(samples)
        pixels = model["full"]["scene"].size
        timings.append(dict(impl=impl, name=name, output=output, times_us=samples, min_us=min(samples),
                            median_us=median, mpixels_per_s=pixels / median))
    if not re.search(r"^IF_CHECK_OK\s*$", log, re.MULTILINE):
        errors.append("the firmware reported IF_CHECK_FAILED (or nothing)")
    clocks = {r["name"]: int(r["mhz"]) for r in records(log, "IF_CLOCK")}
    if sorted(clocks) != ["arm", "core", "sdram", "v3d"]:
        errors.append(f"missing clocks: {clocks}")
    images = {}
    for fields, body in parse_blocks(log, "IF_IMAGE", "IF_IMAGE_END"):
        h, w = int(fields["h"]), int(fields["w"])
        try:
            data = bytes.fromhex("".join(body))
        except ValueError:
            errors.append(f"garbled image {fields['name']}")
            continue
        if len(data) != h * w:
            errors.append(f"image {fields['name']}: {len(data)} bytes, expected {h * w}")
            continue
        images[fields["name"]] = np.frombuffer(data, np.uint8).reshape(h, w)
    if dump and sorted(images) != sorted(o for o in PI_DUMP if any(filters.OUTPUTS[n] == o for n in names)):
        errors.append(f"expected dumped images, got {sorted(images)}")
    if errors:
        raise ValueError("Pi run rejected:\n  " + "\n  ".join(errors))
    return dict(timings=timings, clocks_mhz=clocks, rows_checked=checked_rows,
                arm_checks=list(arm_checks.values()), images=images,
                same_on_board=records(log, "IF_SAME"))


def summarize(result: dict, names: list) -> tuple[str, dict]:
    """A text table and the speedups: per output, the best QPU filter against
    the best ARM implementation, and each QPU filter against the ARM direct one."""
    by = {(t["impl"], t["name"]): t for t in result["timings"]}
    lines = [f"{'filter':22s} {'QPU ms':>8s} {'Mpix/s':>8s} {'+icache':>8s}   vs ARM direct   vs best ARM"]
    speedups = {}
    for output in OUTPUTS:
        arms = {a: by[("arm", a)] for a, (o, _) in ARM_IMPLS.items() if o == output and ("arm", a) in by}
        direct = next((by[("arm", a)] for a, (o, k) in ARM_IMPLS.items() if o == output and k == "direct"
                       and ("arm", a) in by), None)
        best_arm = min(arms.values(), key=lambda t: t["median_us"]) if arms else None
        qpus = [by[("qpu", n)] for n in names if filters.OUTPUTS[n] == output]
        for t in qpus:
            vs_direct = direct["median_us"] / t["median_us"] if direct else None
            vs_best = best_arm["median_us"] / t["median_us"] if best_arm else None
            icache = by.get(("qpu_icache", t["name"]))
            lines.append(f"{t['name']:22s} {t['median_us'] / 1000:8.3f} {t['mpixels_per_s']:8.1f} "
                         + (f"{icache['median_us'] / 1000:8.3f}   " if icache else f"{'-':>8s}   ")
                         + (f"{vs_direct:10.1f}x   " if vs_direct else f"{'-':>11s}   ")
                         + (f"{vs_best:8.1f}x" if vs_best else f"{'-':>9s}"))
        for name, t in arms.items():
            lines.append(f"  {name:20s} {t['median_us'] / 1000:8.3f} {t['mpixels_per_s']:8.1f}            (ARM)")
        if qpus and best_arm:
            best_qpu = min(qpus, key=lambda t: t["median_us"])
            speedups[output] = dict(best_qpu=best_qpu["name"], best_qpu_us=best_qpu["median_us"],
                                    best_arm=best_arm["name"], best_arm_us=best_arm["median_us"],
                                    speedup=best_arm["median_us"] / best_qpu["median_us"])
    return "\n".join(lines), speedups


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--width", type=int, default=640)
    ap.add_argument("--height", type=int, default=480)
    ap.add_argument("--check-size", default=f"{CHECK_SIZE[1]}x{CHECK_SIZE[0]}",
                    help="WxH of the small ragged image every filter also runs on")
    ap.add_argument("--repeats", type=int, default=5)
    ap.add_argument("--filters", default=",".join(FILTERS), help="comma-separated subset of " + ",".join(FILTERS))
    ap.add_argument("--build-only", action="store_true", help="compile and build the firmware, nothing else")
    ap.add_argument("--dry-run", action="store_true",
                    help="everything except the boot: build, model, emulator check, docs images")
    ap.add_argument("--dump-images", action="store_true",
                    help="read the Pi's 5x5 blur and blur+Sobel images back (about 55 s of UART each at VGA)")
    ap.add_argument("--build-dir", type=Path, default=ROOT / "build/image_filters")
    ap.add_argument("--images-dir", type=Path, default=ROOT / "docs/images")
    ap.add_argument("--tty")
    ap.add_argument("--timeout", type=float, default=None, help="seconds to wait for the Pi")
    ap.add_argument("--verbose", action="store_true")
    ap.add_argument("--output", type=Path,
                    default=ROOT / f"benchmarks/results/image_filters-pi-{datetime.now():%Y-%m-%d}.json")
    args = ap.parse_args(argv)
    try:
        cw, ch = (int(v) for v in args.check_size.lower().split("x"))
    except ValueError:
        ap.error("--check-size must be WxH")
    args.check_size = (ch, cw)
    names = [n for n in args.filters.split(",") if n]
    unknown = sorted(set(names) - set(FILTERS))
    if unknown or not names:
        ap.error(f"unknown filters {unknown}; choose from {FILTERS}")
    names = [n for n in FILTERS if n in names]        # main.c's order: the first of each output writes it
    if args.repeats < 1 or min(args.width, args.height, cw, ch) < 1:
        ap.error("sizes and --repeats must be positive")
    if (cw > args.width or ch > args.height):
        ap.error("--check-size must fit in the full image")
    if not (args.build_only or args.dry_run) and (args.tty or find_tty()) is None:
        raise SystemExit("No Pi found: plug in the USB serial adapter (or set PITON_TTY / --tty), "
                         "or use --dry-run to do everything except the boot")
    if not (args.build_only or args.dry_run) and find_bootloader() is None:
        raise SystemExit("No bootloader found: put my-install or pi-install on PATH (or set PITON_BOOTLOADER)")

    started = time.monotonic()
    print(f"Compiling {len(names)} filters for {args.width}x{args.height}:", flush=True)
    binary, manifest, compiled = build_firmware(args, names)
    print(f"Built {binary.stat().st_size:,}-byte firmware: {binary}", flush=True)
    if args.build_only:
        return
    print("Host model (numpy + PIton's sqrt on the emulator)...", flush=True)
    model = host_model(args)
    print(f"Strict emulator at the check size ({cw}x{ch}):", flush=True)
    emulator_check(names, compiled, model)
    for path in write_model_images(model, args.images_dir):
        print(f"Wrote {path.relative_to(ROOT) if path.is_relative_to(ROOT) else path}", flush=True)
    if args.dry_run:
        print(f"Dry run done in {time.monotonic() - started:.0f} s; the boot would run {binary}")
        return

    timeout = args.timeout or (120 + (70 * len(PI_DUMP) if args.dump_images else 0))
    try:
        runner = PiRunner(tty=args.tty, timeout=timeout, verbose=args.verbose)
        boot_started = time.monotonic()
        log = runner._boot_recovering(str(binary))
    except PiError as ex:
        if ex.log:
            failed = args.output.with_name(args.output.stem + "-failed.log")
            failed.parent.mkdir(parents=True, exist_ok=True)
            failed.write_text(ex.log)
            print(f"Partial log saved to {failed}", file=sys.stderr)
        raise SystemExit(f"Pi run failed: {ex}")
    boot_seconds = time.monotonic() - boot_started
    args.output.parent.mkdir(parents=True, exist_ok=True)
    log_path = args.output.with_suffix(".log")
    log_path.write_text(log)            # kept even when the run is rejected below
    try:
        result = parse_log(log, names, model, args.repeats, dump=args.dump_images)
    except ValueError as ex:
        raise SystemExit(f"{ex}\nRaw log: {log_path}")
    table, speedups = summarize(result, names)
    images = result.pop("images")
    for name, pixels in images.items():
        reference = filters.display(name, model["full"][name])
        differ = int((pixels != reference).sum())
        result.setdefault("dumped_images", {})[name] = dict(
            pixels_differing_from_model=differ, max_level_difference=int(np.abs(
                pixels.astype(int) - reference.astype(int)).max()))
        path = args.images_dir / f"image_filters-pi-{name}.png"
        filters.write_png(str(path), pixels)
        print(f"Wrote {path} (from the Pi; {differ} pixels differ from the model's PNG, by at most "
              f"{result['dumped_images'][name]['max_level_difference']} level)", flush=True)
    result.update(manifest=manifest, speedups=speedups, timestamp_utc=datetime.now(timezone.utc).isoformat(),
                  boot_and_run_seconds=boot_seconds,
                  raw_log=str(log_path.relative_to(ROOT)) if log_path.is_relative_to(ROOT) else str(log_path),
                  timing_scope="QPU: the whole generated launch call(s) (uniforms, cache clears, queueing, "
                               "waiting), median of repeats; the separable blur is two launches. ARM: the "
                               "whole C function with the L1 caches on, -O3, median of repeats.")
    args.output.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    print(f"\nPi verified: {result['rows_checked']} row hashes equal the model "
          f"({len(names)} filters at {args.width}x{args.height} and {cw}x{ch}); "
          f"every ARM comparison passed. Clocks: {result['clocks_mhz']}\n")
    print(table)
    for output, s in speedups.items():
        print(f"{output}: best QPU {s['best_qpu']} {s['best_qpu_us'] / 1000:.3f} ms, best ARM "
              f"{s['best_arm']} {s['best_arm_us'] / 1000:.3f} ms, {s['speedup']:.1f}x")
    print(f"\nSaved {args.output} and {log_path}")


if __name__ == "__main__":
    main()
